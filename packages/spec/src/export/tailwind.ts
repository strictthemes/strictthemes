import { tokensForMode } from '../resolve.ts'
import type { StrictSpec } from '../types.ts'
import { block, fontStack, slug, textScaleVars } from './shared.ts'

/**
 * Tailwind CSS v4 theme: an `@theme` block of design tokens, plus one class
 * per extra mode (`.dark { … }`) that overrides the colors that mode changes.
 *
 * Font families get one `--font-*` variable each, named after the first
 * typography token that uses them. Each typography token becomes a
 * `text-<token>` utility, and each spacing token a `space-<token>` size.
 */
export function toTailwindCss(spec: StrictSpec): string {
  const theme: [string, string][] = []

  for (const [name, value] of Object.entries(spec.colors)) {
    theme.push([`--color-${slug(name)}`, value])
  }

  const families = new Set<string>()
  for (const [name, token] of Object.entries(spec.typography)) {
    if (typeof token.fontFamily !== 'string') continue
    const family = fontStack(token.fontFamily)
    if (families.has(family)) continue
    families.add(family)
    theme.push([`--font-${slug(name)}`, family])
  }

  for (const [name, value] of textScaleVars(spec.typography)) {
    theme.push([`--${name}`, value])
  }

  for (const [name, value] of Object.entries(spec.rounded)) {
    theme.push([`--radius-${slug(name)}`, value])
  }
  // Spacing tokens are prefixed (`p-space-md`): in Tailwind v4 a variable named
  // `--spacing-md` would also become the value of `max-w-md` and `w-md`.
  for (const [name, value] of Object.entries(spec.spacing)) {
    theme.push([`--spacing-space-${slug(name)}`, value])
  }

  const parts = [`/* ${spec.name} — generated by @strictthemes/spec */\n`, block('@theme', theme)]
  for (const [mode, { colors }] of Object.entries(spec.strict.modes)) {
    const resolved = tokensForMode(spec, mode).colors
    parts.push(
      block(
        `.${slug(mode)}`,
        Object.keys(colors).map((name) => [`--color-${slug(name)}`, resolved[name] ?? '']),
      ),
    )
  }
  return parts.filter(Boolean).join('\n')
}
